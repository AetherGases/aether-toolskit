-- =========================================
-- MVP DATABASE
-- =========================================

-- CREATE TYPE

CREATE TYPE status_employee AS ENUM (
    'ACTIVE',
    'INACTIVE',
    'IN_VACATION'
);

CREATE TYPE status_inventory AS ENUM (
    'pending',
    'in review',
    'approved'
);

CREATE TYPE company_size AS ENUM (
    'pequeno',
    'medio',
    'grande'
);


-- =========================================
-- REF
-- =========================================

CREATE TABLE addresses (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zip_code CHAR(8),
    street VARCHAR(255) NOT NULL,
    number VARCHAR(20) NOT NULL,
    complement VARCHAR(150),
    city VARCHAR(150) NOT NULL,
    neighborhood VARCHAR(150) NOT NULL,
    state VARCHAR(150) NOT NULL,
    country VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE companies (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    trade_name VARCHAR(150) UNIQUE,
    cnpj CHAR(14) NOT NULL UNIQUE,
    size company_size,
    registration_date DATE,
    tax_id VARCHAR(50),
    email VARCHAR(255),
    address_id INT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (address_id) REFERENCES addresses (id)
);

CREATE TABLE units (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    company_id INT,
    address_id INT,
    cnpj CHAR(14) NOT NULL UNIQUE,
    cnae VARCHAR(50),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (company_id) REFERENCES companies (id),
    FOREIGN KEY (address_id) REFERENCES addresses (id),
    CONSTRAINT uq_units_company_name UNIQUE (company_id, name)
);

CREATE TABLE sectors (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(255),
    unit_id INT,
    company_id INT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (company_id) REFERENCES companies (id),
    FOREIGN KEY (unit_id) REFERENCES units (id)
);


-- =========================================
-- STORAGE
-- =========================================

CREATE TABLE storage_files (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    path VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


-- =========================================
-- PERMISSIONS
-- =========================================

CREATE TABLE permission_groups (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    company_id INT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_permission_groups_company
        FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT uq_permission_groups_company_name
        UNIQUE (company_id, name)
);

CREATE TABLE permissions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(255),
    pattern VARCHAR(150) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE permission_group_permissions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_group_id INT,
    permission_id INT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (permission_id) REFERENCES permissions (id),
    FOREIGN KEY (permission_group_id) REFERENCES permission_groups (id),
    CONSTRAINT uq_permission_group_permission
        UNIQUE (permission_group_id, permission_id)
);


-- =========================================
-- EMPLOYEE
-- =========================================

CREATE TABLE employees (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf CHAR(11) NOT NULL UNIQUE,
    company_id INT,
    permission_group_id INT,
    unit_id INT,
    sector_id INT,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    status status_employee NOT NULL DEFAULT 'ACTIVE',
    storage_file_id INT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (company_id) REFERENCES companies (id),
    FOREIGN KEY (permission_group_id)
        REFERENCES permission_groups (id),
    FOREIGN KEY (unit_id) REFERENCES units (id),
    FOREIGN KEY (sector_id) REFERENCES sectors (id),
    FOREIGN KEY (storage_file_id) REFERENCES storage_files (id)
);

CREATE TABLE password_recoveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT NOT NULL,
    code_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    attempts SMALLINT NOT NULL DEFAULT 0
        CHECK (attempts BETWEEN 0 AND 5),
    used_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_password_recoveries_employee
        FOREIGN KEY (employee_id)
        REFERENCES employees (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_password_recoveries_employee
    ON password_recoveries (employee_id);


-- =========================================
-- INVENTORY
-- =========================================

CREATE TABLE inventories (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INT NOT NULL,
    employee_id INT NOT NULL,
    sector_id INT NOT NULL,
    file_size FLOAT CHECK (file_size >= 0),
    status status_inventory NOT NULL DEFAULT 'pending',
    file_path VARCHAR(255),
    start_period DATE NOT NULL,
    end_period DATE NOT NULL,
    submission_date DATE,
    type VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (company_id) REFERENCES companies (id),
    FOREIGN KEY (employee_id) REFERENCES employees (id),
    FOREIGN KEY (sector_id) REFERENCES sectors (id),
    CONSTRAINT chk_inventories_period
        CHECK (end_period > start_period)
);


-- =========================================
-- SUBSCRIPTION
-- =========================================

CREATE TABLE plans (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255),
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    duration_days INT NOT NULL CHECK (duration_days > 0),
    currency VARCHAR(10) NOT NULL DEFAULT 'Reais',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE subscriptions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INT,
    plan_id INT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    installments BOOLEAN NOT NULL DEFAULT TRUE,
    deactivated_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (company_id) REFERENCES companies (id),
    FOREIGN KEY (plan_id) REFERENCES plans (id)
);

CREATE UNIQUE INDEX uq_subscriptions_company_active
    ON subscriptions (company_id)
    WHERE is_active = TRUE;


-- =========================================
-- GAS
-- =========================================

CREATE TABLE gases (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    type VARCHAR(100),
    measurement VARCHAR(50),
    gwp FLOAT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sector_gases (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sector_id INT NOT NULL,
    gas_id INT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (sector_id) REFERENCES sectors (id),
    FOREIGN KEY (gas_id) REFERENCES gases (id),
    CONSTRAINT uq_sector_gas UNIQUE (sector_id, gas_id)
);

CREATE TABLE gas_reductions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gas_id INT NOT NULL,
    unit VARCHAR(50),
    current_emission FLOAT,
    estimated_days INT,
    estimated_reduction FLOAT,
    estimated_roi NUMERIC(12,2)
        CHECK (estimated_roi >= 0),
    init_emission FLOAT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (gas_id) REFERENCES gases (id)
);

CREATE TABLE gas_reduction_inventories (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gas_reduction_id INT NOT NULL,
    inventory_id INT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (gas_reduction_id)
        REFERENCES gas_reductions (id),
    FOREIGN KEY (inventory_id)
        REFERENCES inventories (id),
    CONSTRAINT uq_gas_reduction_inventory
        UNIQUE (gas_reduction_id, inventory_id)
);

CREATE TABLE gas_reduction_sectors (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gas_reduction_id INT NOT NULL,
    sector_id INT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (gas_reduction_id)
        REFERENCES gas_reductions (id),
    FOREIGN KEY (sector_id) REFERENCES sectors (id),
    CONSTRAINT uq_gas_reduction_sector
        UNIQUE (gas_reduction_id, sector_id)
);


-- =========================================
-- ROI
-- =========================================

CREATE TABLE roi_analyses (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_id INT NOT NULL,
    calculation_date DATE,
    years_along INT,
    annual_operating_savings NUMERIC(12,2)
        CHECK (annual_operating_savings >= 0),
    estimated_payback_month FLOAT,
    carbon_credit_revenue NUMERIC(12,2)
        CHECK (carbon_credit_revenue >= 0),
    annual_rate_technology_degradation FLOAT,
    wacc FLOAT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (inventory_id) REFERENCES inventories (id)
);

CREATE TABLE roi_projection_years (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roi_analysis_id INT NOT NULL,
    year INT,
    value FLOAT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (roi_analysis_id)
        REFERENCES roi_analyses (id)
);
