-- GAS 

CREATE TABLE gas (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100),
  type VARCHAR(100),
  measurement VARCHAR(50),
  gwp FLOAT
);


CREATE TABLE sector_gas (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sector INT,
  id_gas INT,
  FOREIGN KEY (id_sector) REFERENCES sector(id),
  FOREIGN KEY (id_gas) REFERENCES gas(id)
);

CREATE TABLE gas_reduction 
( 
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  
  id_gas INT,  
  unit VARCHAR(50),  
  current_emission FLOAT,  
  estimated_days INT,  
  estimated_reduction FLOAT,  
  estimated_roi FLOAT,  
  init_emission FLOAT,  
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(id_gas) REFERENCES gas (id),
);

CREATE TABLE reduction_gas (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_gas_reduction INT,
  id_gas INT,
  FOREIGN KEY (id_gas_reduction) REFERENCES gas_reduction(id),
  FOREIGN KEY (id_gas) REFERENCES gas(id)
);

CREATE TABLE gas_reduction_inventory
( id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_gas_reduction INT,  
  id_inventory INT,   
  FOREIGN KEY(id_gasReduction) REFERENCES gas_reduction (id),
  FOREIGN KEY(id_inventory) REFERENCES inventory (id)
); 

CREATE TABLE gas_reduction_sector 
( id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
  id_gas_reduction INT,  
  id_sector INT,  
  FOREIGN KEY(id_gasReduction) REFERENCES gas_reduction (id),
  FOREIGN KEY(id_sector) REFERENCES sector (id)
  
);

